REVOKE ALL ON TABLE public.shipments FROM anon, authenticated, PUBLIC;
ALTER TABLE public.shipments ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.shipments TO authenticated;

CREATE POLICY "Authenticated users can read shipments"
ON public.shipments FOR SELECT TO authenticated
USING (true);

CREATE POLICY "Authenticated users can create shipments"
ON public.shipments FOR INSERT TO authenticated
WITH CHECK (true);

CREATE POLICY "Authenticated users can update shipments"
ON public.shipments FOR UPDATE TO authenticated
USING (true)
WITH CHECK (true);

CREATE POLICY "Authenticated users can delete shipments"
ON public.shipments FOR DELETE TO authenticated
USING (true);

CREATE TABLE IF NOT EXISTS public.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id text NOT NULL,
  action text NOT NULL,
  username text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

REVOKE ALL ON TABLE public.audit_logs FROM anon, authenticated, PUBLIC;
ALTER TABLE public.audit_logs ENABLE ROW LEVEL SECURITY;
GRANT INSERT ON TABLE public.audit_logs TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.audit_logs_id_seq TO authenticated;

CREATE POLICY "Authenticated users can add audit logs"
ON public.audit_logs FOR INSERT TO authenticated
WITH CHECK (true);
